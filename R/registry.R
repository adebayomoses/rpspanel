# The variable registry: one row per panel variable. It drives build_panel()
# and is what codebook() returns, so every variable's source and
# transformation is documented in one place.
var_row <- function(variable, group, label, unit, source, series,
                    transformation, deps = NA_character_) {
  data.frame(variable = variable, group = group, label = label, unit = unit,
             source = source, series = series, transformation = transformation,
             deps = deps, stringsAsFactors = FALSE)
}

